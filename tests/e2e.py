# End-to-end check against the local dev server (node dev-server.mjs). Saves screenshots to $OUT.
import asyncio, os, sys
from playwright.async_api import async_playwright

BASE = os.environ.get("BASE", "http://localhost:8888")
OUT = os.environ.get("OUT", "/tmp/shots")
PIN = os.environ.get("PIN", "13572468")
os.makedirs(OUT, exist_ok=True)
errors = []

async def shot(page, name, full=True):
    await page.wait_for_timeout(250)
    await page.screenshot(path=f"{OUT}/{name}.png", full_page=full)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True, locale="en-PH")
        page = await ctx.new_page()
        page.on("console", lambda m: errors.append(f"console {m.type}: {m.text}") if m.type == "error" else None)
        page.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))
        await page.goto(BASE + "/")
        await page.wait_for_selector(".item")
        await shot(page, "01-home")
        start = await page.evaluate("() => { const d = new Date(); d.setDate(d.getDate()+10); return d.toISOString().slice(0,10) }")
        await page.fill("#start", start); await page.dispatch_event("#start", "change")
        await page.wait_for_selector(".item .badge")
        await page.click('.item[data-id="videoke"] .add')
        await page.click('.item[data-id="monobloc-chair"] .add')
        await page.click('.item[data-id="monobloc-chair"] .stepper button[data-d="1"]')
        await page.click('.item[data-id="round-table"] .add')
        await page.click('.item[data-id="tent-10x10"] .add')
        await shot(page, "02-home-dates-cart")
        await page.click("#cartgo")
        await page.wait_for_selector("#form")
        await page.fill("[name=name]", "Maria Santos")
        await page.fill("[name=phone]", "0917 123 4567")
        await page.select_option("[name=town]", "Teresa")
        await page.fill("[name=address]", "45 Mabini St., Brgy. Dalig")
        await page.fill("[name=landmark]", "Near the chapel")
        await page.fill("[name=notes]", "Pink theme, set-up by 2 PM")
        await page.check("[name=agree]")
        await shot(page, "03-checkout")
        await page.click("#form [type=submit]")
        await page.wait_for_selector(".gcash-box")
        await shot(page, "04-booking-requested")
        # upload a receipt
        png = f"{OUT}/receipt.png"
        await page.screenshot(path=png, clip={"x": 0, "y": 0, "width": 300, "height": 500})
        await page.set_input_files("#proof [name=file]", png)
        await page.fill("#proof [name=reference]", "1029384756102")
        await page.click("#proof [type=submit]")
        await page.wait_for_selector(".badge.b-warn >> text=Being checked")
        await shot(page, "05-booking-proof-sent")
        await page.click('[data-lang="tl"]')
        await page.wait_for_selector("text=Hinihintay ang deposit")
        await shot(page, "06-booking-tl")
        await page.click('[data-lang="en"]')
        booking_url = page.url

        # ---- admin ----
        ad = await ctx.new_page()
        ad.on("pageerror", lambda e: errors.append(f"admin pageerror: {e}"))
        ad.on("console", lambda m: errors.append(f"admin console {m.type}: {m.text}") if m.type == "error" else None)
        await ad.goto(BASE + "/admin")
        await ad.fill("[name=pin]", "0000"); await ad.click("#login [type=submit]")
        await ad.wait_for_selector("text=Wrong PIN")
        await ad.fill("[name=pin]", PIN); await ad.click("#login [type=submit]")
        await ad.wait_for_selector(".kpis")
        await shot(ad, "10-admin-planning")
        await ad.click('[data-tab="payments"]')
        await ad.click("[data-loadproof]")
        await ad.wait_for_selector(".proof-img")
        await shot(ad, "11-admin-payments")
        await ad.click('[data-pay="verified"]')
        await ad.wait_for_timeout(400)
        await ad.click('[data-tab="bookings"]')
        await ad.click(".bk[data-ref]")
        await ad.wait_for_selector(".sheet")
        await shot(ad, "12-admin-booking-sheet", full=False)
        await ad.evaluate("document.querySelector('.sheet').scrollTop = 900")
        await shot(ad, "13-admin-booking-sheet-2", full=False)
        # mark delivered, damage, cash, returned
        await ad.click('[data-status="out"]'); await ad.wait_for_timeout(300)
        await ad.fill("#dmgf [name=charge]", "200"); await ad.fill("#dmgf [name=note]", "1 chair cracked")
        await ad.select_option("#dmgf [name=itemId]", "monobloc-chair")
        await ad.click("#dmgf [type=submit]"); await ad.wait_for_timeout(400)
        await ad.click("#payf [type=submit]"); await ad.wait_for_timeout(400)
        await ad.click('[data-status="returned"]'); await ad.wait_for_timeout(400)
        await ad.click("#sx")
        await ad.click('[data-tab="stock"]'); await ad.wait_for_selector("[data-item]")
        await shot(ad, "14-admin-stock")
        await ad.click('[data-item="videoke"]'); await ad.wait_for_selector("#itemf")
        await shot(ad, "15-admin-item", full=False)
        await ad.click("#sx")
        await ad.click('[data-tab="more"]'); await ad.wait_for_selector("#setf")
        await ad.fill("[name=gcashNumber]", "0917 555 0123"); await ad.fill("[name=gcashName]", "J. Dela Cruz")
        await ad.click("#setf [type=submit]"); await ad.wait_for_timeout(300)
        await shot(ad, "16-admin-more")
        await ad.click('[data-tab="bookings"]')
        await ad.click("#newbk"); await ad.wait_for_selector("#nbitems input")
        await ad.fill("#nbf [name=name]", "Jun Reyes"); await ad.fill("#nbf [name=phone]", "09281112222"); await ad.fill("#nbf [name=address]", "12 Rizal Ave, Brgy. San Roque")
        await ad.fill('#nbitems [data-q="tiffany-chair"]', "40"); await ad.check("#nbf [name=confirmed]")
        await ad.click("#nbf [type=submit]"); await ad.wait_for_selector(".sheet-head >> text=Jun Reyes")
        await ad.click("#sx")
        await ad.click('[data-tab="today"]')
        await shot(ad, "17-admin-planning-after")
        # customer sees final state
        await page.goto(booking_url); await page.reload(); await page.wait_for_selector("text=Completed")
        await shot(page, "07-booking-completed")
        # desktop
        dk = await b.new_page(viewport={"width": 1280, "height": 860})
        await dk.goto(BASE + "/"); await dk.wait_for_selector(".item")
        await shot(dk, "20-desktop-home", full=False)
        await b.close()
    print("\n".join(errors) or "no console errors")

asyncio.run(main())
