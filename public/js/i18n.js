const LANG_KEY = "pahina.lang";
export function getLang() {
  try { const l = localStorage.getItem(LANG_KEY); if (l === "en" || l === "tl") return l; } catch {}
  return (navigator.language || "").toLowerCase().startsWith("fil") || (navigator.language || "").toLowerCase().startsWith("tl") ? "tl" : "en";
}
export function setLang(l) { try { localStorage.setItem(LANG_KEY, l); } catch {} document.documentElement.lang = l === "tl" ? "tl" : "en"; }
export function t(key, vars = {}, lang = getLang()) {
  const s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
export function tr(obj, lang = getLang()) { return (obj && (obj[lang] || obj.en)) || ""; }
export function tLang(lang) { return (key, vars) => t(key, vars, lang); }
